#!/usr/bin/env python3
"""Writes src/UpdateKey.hpp for a P-256 public key PEM: python scripts/update-key-header.py key.pem src/UpdateKey.hpp

It writes the file itself, as UTF-8 with LF endings, because a shell redirect can change the encoding
(Windows PowerShell 5.1 writes UTF-16) and the test compares bytes.
"""
import base64
import sys

# SubjectPublicKeyInfo for a P-256 key is this fixed prefix followed by the 65-byte uncompressed point.
P256_PREFIX = bytes.fromhex("3059301306072a8648ce3d020106082a8648ce3d030107034200")


def key_header(pem_text: str) -> str:
    body = "".join(line for line in pem_text.splitlines() if line and not line.startswith("-----"))
    der = base64.b64decode(body)
    if len(der) != len(P256_PREFIX) + 65 or not der.startswith(P256_PREFIX) or der[len(P256_PREFIX)] != 0x04:
        raise SystemExit("Not an uncompressed P-256 public key")
    point = der[len(P256_PREFIX):]
    rows = [", ".join(f"0x{b:02x}" for b in point[i:i + 13]) for i in range(0, 65, 13)]
    return (
        "#pragma once\n"
        "#include <array>\n"
        "#include <cstdint>\n"
        "// The release signing key from scripts/update-signing-public.pem, as an uncompressed P-256 point.\n"
        "// Generated by scripts/update-key-header.py; tools/qa/test_update_manifest.py checks they match.\n"
        "inline constexpr std::array<uint8_t, 65> UPDATE_PUBLIC_KEY{\n    "
        + ",\n    ".join(rows)
        + "};\n"
    )


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: update-key-header.py public-key.pem src/UpdateKey.hpp")
    with open(sys.argv[1], encoding="ascii") as source, open(sys.argv[2], "w", encoding="utf-8", newline="\n") as target:
        target.write(key_header(source.read()))
